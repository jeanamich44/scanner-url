def _validate_content(endpoint: str, status: int, ct: str, body: str, cl: int, baseline_len: Optional[int] = None) -> Tuple[bool, str, str]:
    if status not in (200, 201, 202, 204):
        return False, "none", ""
    if cl == 0 and not body:
        return False, "none", ""

    if baseline_len is not None and baseline_len > 0:
        if abs(cl - baseline_len) <= 48:
            return False, "none", "Soft-404 détecté"
        if baseline_len > 1000 and abs(cl - baseline_len) / baseline_len < 0.015:
            return False, "none", "Soft-404 détecté"

    ct_lower = (ct or "").lower()
    body_head = (body[:400] if body else "").lower()
    is_html = ("text/html" in ct_lower) or ("<!doctype html" in body_head) or ("<html" in body_head)

    ep_clean = endpoint.split("?")[0].split("#")[0].strip().lower()

    if any(ep_clean.endswith(ext) for ext in [
        ".env", ".env.php", ".env.bak", ".env.old", ".env.save", ".env.backup",
        ".env.stage", ".env.staging", ".env.test", ".env.prod", ".env.production",
        ".env.local", ".env.dev", ".env.development", ".env.dist", ".env.swp",
        ".env.example", ".env.sample", ".env.live", ".env.docker", ".env.testing",
        ".env.txt", ".env~", "sendgrid.env", "config.env"
    ]) or "/.env" in ep_clean or ep_clean == "env":
        if is_html:
            if "<pre" not in body_head and "<code" not in body_head:
                return False, "none", "Faux positif HTML sur .env"
        has_env_kv = bool(re.search(r"^[A-Za-z0-9_]{2,}\s*=\s*[^\r\n]+", body, re.MULTILINE))
        if not has_env_kv and not any(k in body.upper() for k in ["APP_KEY=", "DB_HOST=", "DB_PASSWORD=", "DATABASE_URL="]):
            return False, "none", "Structure .env invalide"
        return True, "high", "Fichier d'environnement .env accessible"

    if ep_clean.endswith(".json"):
        if is_html:
            return False, "none", "Faux positif HTML sur .json"
        try:
            parsed = json.loads(body)
            if isinstance(parsed, (dict, list)):
                return True, "high", f"JSON valide ({ct_lower.split(';')[0] if ct_lower else 'json'})"
        except Exception:
            return False, "none", "Contenu JSON invalide"

    if ".git" in ep_clean:
        if is_html:
            return False, "none", "Faux positif HTML sur Git"
        if ep_clean.endswith("/config") or ep_clean.endswith(".git/config"):
            if "[core]" in body.lower() or "repositoryformatversion" in body.lower():
                return True, "critical", "Configuration Git exposée ([core])"
            return False, "none", "Structure Git config invalide"
        if ep_clean.endswith("/head") or ep_clean.endswith(".git/head"):
            s_body = body.strip()
            if s_body.startswith("ref: refs/") or (len(s_body) == 40 and all(c in "0123456789abcdefABCDEF" for c in s_body)):
                return True, "critical", "Pointeur Git HEAD exposé"
            return False, "none", "Structure Git HEAD invalide"
        if ep_clean.endswith("/index") or ep_clean.endswith(".git/index"):
            if body.startswith("DIRC"):
                return True, "critical", "Index Git binaire exposé (DIRC)"
            return False, "none", "Signature Git index invalide"
        if ep_clean.endswith(".git-credentials"):
            if "http://" in body or "https://" in body:
                return True, "critical", "Identifiants Git exposés"
            return False, "none", "Structure Git-credentials invalide"

    if ep_clean.endswith((".sql", ".dump")) or "/db.sql" in ep_clean or "/dump.sql" in ep_clean or "/backup.sql" in ep_clean:
        if is_html:
            return False, "none", "Faux positif HTML sur fichier SQL"
        sql_markers = ["create table", "insert into", "drop table", "mysqldump", "pg_dump", "-- table structure", "-- phpmyadmin", "mariadb dump"]
        b_lower = body.lower()
        if any(m in b_lower for m in sql_markers):
            return True, "critical", "Base de données SQL exposée"
        return False, "none", "Structure SQL absente"

    if ep_clean.endswith((".zip", ".tar.gz", ".tar", ".tgz", ".gz", ".7z", ".rar")):
        if is_html or "text/html" in ct_lower:
            return False, "none", "Faux positif HTML sur archive"
        return True, "high", f"Archive téléchargeable ({cl} octets)"

    if ep_clean.endswith((".yml", ".yaml")):
        if is_html:
            return False, "none", "Faux positif HTML sur YAML"
        return True, "medium", "Fichier YAML accessible"

    if ep_clean.endswith("wp-admin/install.php") or "/wp-admin/install.php" in ep_clean:
        b_lower = body.lower()
        if any(w in b_lower for w in ["already installed", "déjà installé", "deja installe", "d&#233;j", "already"]):
            return True, "info", "WordPress déjà installé (non vulnérable)"
        if "wp-core-ui" in b_lower or "language-chooser" in b_lower or "<title>wordpress" in b_lower:
            return True, "high", "Installation WordPress non finalisée"
        return False, "none", "Fausse page install.php"

    if ep_clean.endswith("phpinfo.php") or "phpinfo" in ep_clean:
        if "phpinfo()" in body or "php version" in body.lower():
            return True, "medium", "Configuration phpinfo() exposée"
        return False, "none", "Faux phpinfo"

    if is_html:
        has_web_ext = any(ep_clean.endswith(ext) for ext in [".php", ".html", ".htm", "/", ".jsp", ".asp", ".aspx"])
        if not has_web_ext and not any(k in ep_clean for k in ["admin", "login", "server-status", "telescope"]):
            return False, "none", "Page HTML inattendue sur ressource binaire/config"

    sens_labels, _ = _check_sensitive(body)
    if sens_labels:
        return True, "critical", ", ".join(sens_labels)

    sev = _classify(status, cl, sens_labels, ct)
    cap = f"{status} Accessible ({ct_lower.split(';')[0]})" if ct_lower else f"{status} Accessible"
    return True, sev, cap

