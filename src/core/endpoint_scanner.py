async def probe_fast(
    session: AsyncSession,
    base_url: str,
    endpoint: str,
    score: Any,
    timeout: float,
    use_bypass: bool,
    use_mutations: bool,
    headers: Optional[Dict[str, str]] = None,
    baseline_len: Optional[int] = None,
) -> Dict[str, Any]:
    result: Dict[str, Any] = {
        "endpoint": endpoint,
        "score": score,
        "status": None,
        "severity": "none",
        "accessible": False,
        "content_length": 0,
        "content_type": "",
        "response_time_ms": 0,
        "sensitive_data": [],
        "sensitive_matches": [],
        "snippet": "",
        "banned": False,
        "ban_reason": "",
        "capture": "",
    }

    url = base_url.rstrip("/") + endpoint
    browser_tag = "chrome"
    if hasattr(session, "impersonate") and session.impersonate:
        imp_lower = str(session.impersonate).lower()
        if "firefox" in imp_lower:
            browser_tag = "firefox"
        elif "safari" in imp_lower:
            browser_tag = "safari"

    if headers:
        hdrs = sanitize_headers(headers, browser_tag)
    else:
        _, hdrs = get_browser_profile(browser_tag)

    try:
        t0 = time.time()
        resp = await session.get(url, headers=hdrs, timeout=timeout, allow_redirects=False)
        result["response_time_ms"] = round((time.time() - t0) * 1000, 1)
        status = resp.status_code
        result["status"] = status

        body = ""
        try:
            body = resp.text
        except Exception:
            pass

        ban_reason = _detect_ban(status, resp.headers, body)
        if ban_reason:
            result["banned"] = True
            result["ban_reason"] = ban_reason
            result["severity"] = "none"
            result["accessible"] = False
            return result

        if status == 404:
            return result

        if status in (200, 201, 202, 204):
            info = _analyze_resp(resp, endpoint=endpoint, baseline_len=baseline_len)
            result.update(info)
            return result

        if status in (301, 302, 307, 308):
            result["severity"] = "info"
            return result

        if status in (401, 403):
            result["severity"] = "low"

            if use_bypass:
                for bh in BYPASS_HEADERS:
                    try:
                        resp2 = await session.get(url, headers={**hdrs, **bh}, timeout=timeout, allow_redirects=False)
                        if resp2.status_code in (200, 201, 202):
                            result.update(_analyze_resp(resp2, endpoint=endpoint, baseline_len=baseline_len))
                            return result
                    except Exception:
                        pass

            if use_mutations:
                for mutate in PATH_MUTATIONS[:4]:
                    try:
                        mut_url = base_url.rstrip("/") + mutate(endpoint)
                        resp3 = await session.get(mut_url, headers=hdrs, timeout=timeout, allow_redirects=False)
                        if resp3.status_code in (200, 201, 202):
                            result.update(_analyze_resp(resp3, endpoint=endpoint, baseline_len=baseline_len))
                            return result
                    except Exception:
                        pass

            return result

        if status >= 500:
            result["severity"] = "medium"

        return result

    except Exception:
        return result

    except Exception:
        return result
