def _analyze_resp(resp, endpoint: str = "", baseline_len: Optional[int] = None) -> Dict[str, Any]:
    status = resp.status_code
    ct = resp.headers.get("content-type", "")
    body = ""
    cl = 0
    try:
        body = resp.text
        cl = len(resp.content)
    except Exception:
        cl = int(resp.headers.get("content-length", 0))

    ban_reason = _detect_ban(status, resp.headers, body)
    if ban_reason:
        return {
            "status": status,
            "content_length": cl,
            "content_type": ct,
            "severity": "none",
            "sensitive_data": [],
            "sensitive_matches": [],
            "snippet": "",
            "accessible": False,
            "banned": True,
            "ban_reason": ban_reason,
            "capture": "",
        }

    is_valid, sev, cap = _validate_content(endpoint, status, ct, body, cl, baseline_len)
    sens_labels, sens_matches = _check_sensitive(body) if body else ([], [])
    if sens_labels and status == 200 and is_valid:
        sev = "critical"
        cap = ", ".join(sens_labels)

    snippet = body[:1500] if body else ""
    return {
        "status": status,
        "content_length": cl,
        "content_type": ct,
        "severity": sev,
        "sensitive_data": sens_labels,
        "sensitive_matches": sens_matches,
        "snippet": snippet,
        "accessible": is_valid,
        "banned": False,
        "ban_reason": "",
        "capture": cap,
    }

