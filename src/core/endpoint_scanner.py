def _sort_endpoint(ep: Dict[str, Any]):
    val = ep.get("score")
    if isinstance(val, str):
        v = val.strip().lower()
        if v.startswith("top-") or v.startswith("top"):
            num = v.replace("top-", "").replace("top", "").strip()
            try:
                return (0, float(num))
            except ValueError:
                pass
    elif isinstance(val, (int, float)):
        return (1, -float(val))
    return (2, 0.0)

