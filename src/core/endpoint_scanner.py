def _detect_ban(status: int, headers: Any, body: str) -> Optional[str]:
    if status == 429:
        return "HTTP 429 Too Many Requests"
    hdr_txt = ""
    if hasattr(headers, "items"):
        hdr_txt = " ".join(f"{k}:{v}" for k, v in headers.items()).lower()
    elif isinstance(headers, dict):
        hdr_txt = " ".join(f"{k}:{v}" for k, v in headers.items()).lower()
    elif isinstance(headers, str):
        hdr_txt = headers.lower()

    if status in (200, 401, 403, 503):
        if "cf-ray" in hdr_txt and any(k in body.lower() for k in ["cloudflare", "just a moment", "challenge", "turnstile", "attention required"]):
            return "Cloudflare Challenge"
        if "x-amzn-waf-action" in hdr_txt or "awswaf" in hdr_txt:
            return "AWS WAF Block"
        for pat, reason in BAN_SIGNATURES:
            if pat.search(body):
                return reason
    return None

