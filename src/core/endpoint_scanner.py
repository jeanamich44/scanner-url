def _check_sensitive(body: str):
    labels = []
    matches = []
    for label, pat in SENSITIVE_DEFINITIONS:
        m = pat.search(body)
        if m:
            labels.append(label)
            matched_val = m.group(0)[:120]
            matches.append(matched_val)
    return labels, matches

